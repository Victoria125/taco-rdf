"""Recount which TACO foods have a FoodOn type in four independent ways; have Lean check the counts claimed.

A: the publication rule of docs/foodon-typing.md applied afresh to data/alignment/alignments.csv: a type row
   to a class of the pinned FoodOn release with no whole organism or plant among its ancestors, asked of
   Fuseki;
B: build/taco.ttl, read with rdflib;
C: the TACO foods in Fuseki's nicefood dataset;
D: analysis/data/foodon_types.csv and foodon_typing_gaps.csv, written by scripts/audit_foodon_typing.py.

It then sorts the untyped foods by what the alignment inputs keep for them and by whether round 1 sampled
them, and writes build/verification/TacoTypingState.lean: verification/lean/TacoTyping.lean followed by the
597 foods as data and theorems stating the counts claimed. Lean (with Mathlib, as in verification/lean's
lakefile) checks them, and fails if any claim is false. --lake-project names a Lake project whose Mathlib
build to use, if verification/lean has none.

    $env:PYTHONPATH = "src"; python verification/taco_typing_state.py --lake-project C:/path/to/project
"""

from __future__ import annotations

import argparse
import csv
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import requests
from rdflib import RDF, Graph

from taco_rdf import sparql as sparql_store
from taco_rdf.namespaces import TACO_SOURCE as TACO_IRI

ROOT = Path(__file__).resolve().parents[1]
ENDPOINT = sparql_store.endpoint()
OBO = "http://purl.obolibrary.org/obo/"
ORGANISM_ROOTS = (OBO + "COB_0000022", OBO + "PO_0000003")
TACO_SOURCE = str(TACO_IRI)
OUT = ROOT / "build" / "verification" / "TacoTypingState.lean"
# What the project's reports and the assistant claimed on 2026-11-17.
CLAIMS = {"foods": 597, "typed": 311, "untyped": 286, "untyped_with_candidate": 125,
          "untyped_without_candidate": 161, "untyped_only_blocked": 35, "untyped_in_round1": 90,
          "untyped_not_in_round1": 196}


def sparql(query: str) -> list[dict]:
    r = requests.post(ENDPOINT, data={"query": query},
                      headers={"Accept": "application/sparql-results+json"}, timeout=900)
    r.raise_for_status()
    return r.json()["results"]["bindings"]


def with_organism_ancestor(iris: set[str]) -> set[str]:
    found: set[str] = set()
    items = sorted(iris)
    for i in range(0, len(items), 150):
        values = " ".join(f"<{c}>" for c in items[i:i + 150])
        roots = " ".join(f"<{c}>" for c in ORGANISM_ROOTS)
        rows = sparql("PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#> SELECT DISTINCT ?c WHERE { "
                      f"VALUES ?c {{ {values} }} VALUES ?r {{ {roots} }} ?c rdfs:subClassOf* ?r }}")
        found |= {b["c"]["value"] for b in rows}
    return found


def pinned_release() -> set[str]:
    with (ROOT / "ontology" / "imports" / "foodon-classes.tsv").open(encoding="utf-8") as fh:
        return {OBO + line.split("\t", 1)[0] for line in fh if line.startswith("FOODON_")}


def rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def from_rule(alignments: list[dict[str, str]], blocked: set[str], pinned: set[str]) -> set[int]:
    return {int(r["source_key"]) for r in alignments
            if r["source_type"] == "food" and r["predicate"] in ("type", "rdf:type")
            and r["target_iri"] in pinned and r["target_iri"] not in blocked}


def from_graph(path: Path) -> set[int]:
    g = Graph().parse(path, format="turtle")
    return {int(m.group(1)) for s, o in g.subject_objects(RDF.type)
            if str(o).startswith(OBO + "FOODON_") and (m := re.search(r"/food/(\d+)$", str(s)))}


def from_fuseki() -> set[int]:
    found = sparql("PREFIX dcterms: <http://purl.org/dc/terms/> SELECT DISTINCT ?f WHERE { "
                   f"?f dcterms:isVersionOf <{TACO_SOURCE}> ; a ?c . "
                   f'FILTER STRSTARTS(STR(?c), "{OBO}FOODON_") }}')
    return {int(re.search(r"(\d+)$", b["f"]["value"]).group(1)) for b in found}


def lean_data(foods: list[dict]) -> str:
    def b(x: bool) -> str:
        return "true" if x else "false"
    entries = ",\n  ".join(
        f"⟨{f['num']}, {b(f['A'])}, {b(f['B'])}, {b(f['C'])}, {b(f['D'])}, {b(f['candidate'])}, "
        f"{b(f['only_blocked'])}, {b(f['round1'])}⟩" for f in foods)
    untyped = "(foods.filter (fun f => !f.typed))"
    c = CLAIMS
    return f"""

/-! ## The 597 TACO foods, generated by verification/taco_typing_state.py -/

namespace TacoTypingState
open TacoTyping

set_option maxRecDepth 100000

structure Food where
  num : Nat
  typedA : Bool
  typed : Bool
  typedC : Bool
  typedD : Bool
  candidate : Bool
  onlyBlocked : Bool
  round1 : Bool

def foods : List Food := [
  {entries}]

/-- Every TACO food appears once, numbered 1 to 597. -/
theorem numbered : foods.map (·.num) = (List.range {c['foods']}).map (· + 1) := by decide

/-- The four sources agree on every food. -/
theorem sources_agree :
    foods.all (fun f => f.typedA == f.typed && f.typedC == f.typed && f.typedD == f.typed) = true := by
  decide

theorem n_typed : (foods.filter (·.typed)).length = {c['typed']} := by decide
theorem n_untyped : {untyped}.length = {c['untyped']} := by decide
theorem typed_plus_untyped : (foods.filter (·.typed)).length + {untyped}.length = foods.length :=
  count_split (·.typed) foods
theorem n_with_candidate : ({untyped}.filter (·.candidate)).length = {c['untyped_with_candidate']} := by
  decide
theorem n_without_candidate :
    ({untyped}.filter (fun f => !f.candidate)).length = {c['untyped_without_candidate']} := by decide
theorem n_only_blocked : ({untyped}.filter (·.onlyBlocked)).length = {c['untyped_only_blocked']} := by
  decide
theorem n_in_round1 : ({untyped}.filter (·.round1)).length = {c['untyped_in_round1']} := by decide
theorem n_not_in_round1 : ({untyped}.filter (fun f => !f.round1)).length = {c['untyped_not_in_round1']} := by
  decide

end TacoTypingState
"""


def write_lean(path: Path, text: str) -> None:
    """Write a Lean file with LF line endings on every system, so that checks and mutations see one text."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def check_with_lean(path: Path, lake_project: Path) -> int:
    """Run Lean on path in the environment of a Lake project with Mathlib; print what it says."""
    result = subprocess.run(["lake", "env", "lean", str(path)], cwd=lake_project, capture_output=True,
                            text=True, encoding="utf-8")
    print((result.stdout + result.stderr).strip() or "Lean: every theorem checked")
    return result.returncode


def mutants_rejected(path: Path, lake_project: Path, mutations: list[tuple[str, str, str]]) -> list[str]:
    """Mutation tests of a generated Lean file: each (name, regex, replacement) must change the file, and
    Lean must then reject it. Returns the problems; a mutation that changes nothing is one, so it cannot
    pass unnoticed."""
    text = path.read_text(encoding="utf-8")
    problems = []
    with tempfile.TemporaryDirectory() as tmp:
        for i, (name, pattern, replacement) in enumerate(mutations):
            mutant = re.sub(pattern, replacement, text, count=1)
            if mutant == text:
                problems.append(f"mutation '{name}' did not change the file")
                continue
            target = Path(tmp) / f"Mutant{i}.lean"
            write_lean(target, mutant)
            result = subprocess.run(["lake", "env", "lean", str(target)], cwd=lake_project,
                                    capture_output=True, text=True, encoding="utf-8")
            if result.returncode == 0:
                problems.append(f"mutation '{name}': Lean accepted the mutant")
            else:
                print(f"   mutant '{name}': changed the file, and Lean rejected it")
    return problems


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--lake-project", type=Path, default=ROOT / "verification" / "lean",
                   help="a Lake project with Mathlib built (default verification/lean)")
    p.add_argument("--no-mutants", action="store_true", help="skip the mutation tests of the Lean file")
    args = p.parse_args()
    alignments = rows(ROOT / "data" / "alignment" / "alignments.csv")
    food_rows = [r for r in alignments
                 if r["source_type"] == "food" and r["target_iri"].startswith(OBO + "FOODON_")]
    blocked = with_organism_ancestor({r["target_iri"] for r in food_rows})
    pinned = pinned_release()
    a = from_rule(alignments, blocked, pinned)
    b = from_graph(ROOT / "build" / "taco.ttl")
    c = from_fuseki()
    d = {int(r["food_number"]) for r in rows(ROOT / "analysis" / "data" / "foodon_types.csv")}
    gaps = {int(r["food_number"]) for r in rows(ROOT / "analysis" / "data" / "foodon_typing_gaps.csv")}
    round1 = {int(r["food_number"])
              for r in rows(ROOT / "data" / "alignment" / "review" / "round-1" / "items.csv")}
    candidates: dict[int, set[str]] = {}
    for r in food_rows:
        candidates.setdefault(int(r["source_key"]), set()).add(r["target_iri"])
    print(f"typed by A (rule on alignments.csv) {len(a)}, B (build/taco.ttl) {len(b)}, C (Fuseki) {len(c)}, "
          f"D (audit CSV) {len(d)}; audit gaps {len(gaps)}")
    for name, s in (("A", a), ("C", c), ("D", d)):
        if s != b:
            print(f"  {name} differs from B: only in {name} {sorted(s - b)[:10]}, "
                  f"only in B {sorted(b - s)[:10]}")
    foods = []
    for n in range(1, 598):
        cands = candidates.get(n, set())
        foods.append({"num": n, "A": n in a, "B": n in b, "C": n in c, "D": n in d and n not in gaps,
                      "candidate": bool(cands), "only_blocked": bool(cands) and cands <= blocked,
                      "round1": n in round1})
    untyped = [f for f in foods if not f["B"]]
    print(f"untyped {len(untyped)}: with candidate {sum(f['candidate'] for f in untyped)}, "
          f"without {sum(not f['candidate'] for f in untyped)}, only blocked candidates "
          f"{sum(f['only_blocked'] for f in untyped)}, in round 1 {sum(f['round1'] for f in untyped)}")
    base = (ROOT / "verification" / "lean" / "TacoTyping.lean").read_text(encoding="utf-8")
    write_lean(OUT, base + lean_data(foods))
    print(f"wrote {OUT}; checking with Lean")
    code = check_with_lean(OUT, args.lake_project)
    problems = [] if args.no_mutants else mutants_rejected(OUT, args.lake_project, [
        ("a typed count off by one", rf"(\(foods\.filter \(·\.typed\)\)\.length = ){CLAIMS['typed']}",
         rf"\g<1>{CLAIMS['typed'] + 1}"),
        ("one food typed in one source only", rf"⟨{min(b)}, true, ", f"⟨{min(b)}, false, ")])
    for problem in problems:
        print(f"PROBLEM: {problem}")
    return 1 if code or problems else 0


if __name__ == "__main__":
    sys.exit(main())
